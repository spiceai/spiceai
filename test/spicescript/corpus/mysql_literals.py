"""Writes mysql-literals.sql: postgres_literals.py's matrix for mysql-literals.yaml's
MySQL table `m`, in literal forms both Spice and MySQL read the same way (bare
numbers, quoted strings, DATE and TIMESTAMP keywords; MySQL has no NaN or
infinities). Run: python3 mysql_literals.py > mysql-literals.sql"""

COLUMNS = {
    # column: values in ascending order, as literals; the smallest is also the
    # table's smallest. Each is written as it appears in SQL.
    "f": ["-1.7976931348623157e308", "-1", "0", "5e-324", "2.2250738585072014e-308",
          "0.30000000000000004", "1e308"],
    "d": ["-99999999999999999999999999999999999.999999999999999999999999999999",
          "-0.000000000000000000000000000001", "0", "2.5",
          "99999999999999999999999999999999999.999999999999999999999999999999"],
    "i8": ["-9223372036854775808", "-1", "0", "9223372036854775807"],
    "u8": ["0", "1", "18446744073709551615"],
    "s": ["''", "' '", "'a''b\"c_d%e'", "'naïve'", "'tab\there'", "'日本語'", "'😀 emoji'"],
    "dtm": ["TIMESTAMP '1000-01-01 00:00:00'", "TIMESTAMP '1970-01-01 00:00:00.000001'",
            "TIMESTAMP '2000-02-29 12:00:00.000001'", "TIMESTAMP '2038-01-19 03:14:08'",
            "TIMESTAMP '9999-12-31 23:59:59.999999'"],
    "dt": ["DATE '1000-01-01'", "DATE '1969-12-31'", "DATE '2000-02-29'", "DATE '9999-12-31'"],
}

def emit(sql, col, values, empty=False):
    if empty:
        print("-- expect-empty")
    print(sql)


print("-- Generated by mysql_literals.py; do not edit by hand.")
print("-- Each column of `m` compared with each edge value of its type in each form.")
for col, values in COLUMNS.items():
    print(f"\n-- {col}")
    for i, x in enumerate(values):
        emit(f"SELECT id FROM m WHERE {col} = {x} ORDER BY id;", col, [x])
        emit(f"SELECT id FROM m WHERE {col} < {x} ORDER BY id;", col, [x], empty=i == 0)
        emit(f"SELECT id FROM m WHERE {col} >= {x} ORDER BY id;", col, [x])
        emit(f"SELECT id FROM m WHERE {col} <> {x} ORDER BY id;", col, [x])
    for a, b in zip(values, values[1:]):
        emit(f"SELECT id FROM m WHERE {col} IN ({a}, {b}) ORDER BY id;", col, [a, b])
        emit(f"SELECT id FROM m WHERE {col} BETWEEN {a} AND {b} ORDER BY id;", col, [a, b])
