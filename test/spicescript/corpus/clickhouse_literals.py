"""Writes clickhouse-literals.sql: postgres_literals.py's matrix for
clickhouse-literals.yaml's ClickHouse table `c`, in literal forms both Spice and
ClickHouse read the same way (bare numbers, quoted strings without backslashes),
except that ClickHouse is asked for dates and times with toDate32 and
toDateTime64, since its DATE and TIMESTAMP keywords cover only 1970-2149. Run: python3 clickhouse_literals.py >
clickhouse-literals.sql"""

COLUMNS = {
    # column: values in ascending order, as literals; the smallest is also the
    # table's smallest. Each is written as it appears in SQL.
    # ClickHouse reads subnormal doubles as 0, so its smallest is 1e-300.
    "f": ["-1.7976931348623157e308", "-1", "0", "1e-300", "0.30000000000000004", "1e308"],
    "d": ["-999999999999.999999", "-0.5", "0", "2.5", "999999999999.999999"],
    "i8": ["-9223372036854775808", "-1", "0", "9223372036854775807"],
    "u8": ["0", "1", "18446744073709551615"],
    "s": ["''", "' '", "'a''b\"c_d%e'", "'naïve'", "'日本語'", "'😀 emoji'"],
    "dtm": ["TIMESTAMP '1900-01-01 00:00:00'", "TIMESTAMP '1970-01-01 00:00:00.000001'",
            "TIMESTAMP '2000-02-29 12:00:00.000001'", "TIMESTAMP '2038-01-19 03:14:08'",
            "TIMESTAMP '2261-12-31 23:59:59.999999'"],
    "dt": ["DATE '1900-01-01'", "DATE '1969-12-31'", "DATE '2000-02-29'", "DATE '2299-12-31'"],
}

# ClickHouse reads an IN list of decimals as doubles, so the oracle query
# writes them with toDecimal64.
def oracle(sql):
    """The query in ClickHouse's own date and time functions."""
    sql = sql.replace("DATE '", "toDate32('")
    sql = sql.replace("TIMESTAMP '", "toDateTime64('")
    out, rest = "", sql
    while "('" in rest and ("toDate32('" in rest or "toDateTime64('" in rest):
        head, _, tail = rest.partition("('")
        value, _, rest = tail.partition("'")
        suffix = ", 6, 'UTC')" if head.endswith("toDateTime64") else ")"
        out += f"{head}('{value}'{suffix}"
    return out + rest

def emit(sql, col, values, empty=False):
    if empty:
        print("-- expect-empty")
    if col in ("dt", "dtm"):
        print(f"-- oracle-sql: {oracle(sql).removesuffix(';')}")
    elif col == "d" and " IN (" in sql:
        text = sql.removesuffix(";")
        for v in values:
            text = text.replace(f"({v},", f"(toDecimal64('{v}', 6),").replace(f" {v})", f" toDecimal64('{v}', 6))")
        print(f"-- oracle-sql: {text}")
    print(sql)


print("-- Generated by clickhouse_literals.py; do not edit by hand.")
print("-- Each column of `c` compared with each edge value of its type in each form.")
for col, values in COLUMNS.items():
    print(f"\n-- {col}")
    for i, x in enumerate(values):
        emit(f"SELECT id FROM c WHERE {col} = {x} ORDER BY id;", col, [x])
        emit(f"SELECT id FROM c WHERE {col} < {x} ORDER BY id;", col, [x], empty=i == 0)
        emit(f"SELECT id FROM c WHERE {col} >= {x} ORDER BY id;", col, [x])
        emit(f"SELECT id FROM c WHERE {col} <> {x} ORDER BY id;", col, [x])
    for a, b in zip(values, values[1:]):
        emit(f"SELECT id FROM c WHERE {col} IN ({a}, {b}) ORDER BY id;", col, [a, b])
        emit(f"SELECT id FROM c WHERE {col} BETWEEN {a} AND {b} ORDER BY id;", col, [a, b])
