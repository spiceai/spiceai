"""Writes postgres-literals.sql: every column of edge-values' table `e` compared with
each edge value of its type in each comparison form, so that every path that
rewrites a literal into SQL for another engine (federation, cluster
executors) is checked against PostgreSQL. Run: python3 postgres_literals.py > postgres-literals.sql"""

CAST = "CAST('{v}' AS {t})"
COLUMNS = {
    # column: (SQL type both engines accept, literal values in ascending order
    # (NaN, which PostgreSQL orders above everything, last); the smallest is
    # also the table's smallest, so nothing is below it)
    "f": ("DOUBLE PRECISION", ["-Infinity", "-0", "0", "5e-324", "2.2250738585072014e-308",
                               "0.30000000000000004", "1e308", "Infinity", "NaN"]),
    "r": ("REAL", ["-Infinity", "-0", "1e-45", "0.1", "3.4e38", "Infinity", "NaN"]),
    "d": ("DECIMAL(38, 10)", ["-9999999999999999999999999999.9999999999", "-0.0000000001", "0",
                              "0.0000000001", "2.5", "9999999999999999999999999999.9999999999"]),
    "n": ("DECIMAL(38, 0)", ["-99999999999999999999999999999999999999", "0", "25",
                             "99999999999999999999999999999999999999"]),
    "i8": ("BIGINT", ["-9223372036854775808", "-1", "0", "9223372036854775807"]),
    "i2": ("SMALLINT", ["-32768", "0", "32767"]),
    # Byte order (the table's column is COLLATE "C").
    "s": ("VARCHAR", ["", " ", "a''b\"c\\d_e", "naïve", "tab\there", "日本語", "😀 emoji"]),
    "ts": ("TIMESTAMP", ["1970-01-01 00:00:00", "1970-01-01 00:00:00.000001", "2000-02-29 12:00:00.000001",
                         "2024-03-10 02:30:00", "2100-12-31 23:59:59.999999"]),
    "tz": ("TIMESTAMPTZ", ["1900-01-01 00:00:00+00", "1969-12-31 23:59:59.999999+00", "2024-03-10 01:30:00-08",
                           "2024-03-10 03:30:00-07", "2024-06-30 23:59:59+14", "2024-11-03 01:30:00-07"]),
    "dt": ("DATE", ["1900-01-01", "1969-12-31", "1970-01-01", "2000-02-29", "2100-12-31"]),
}


def lit(t, v):
    return CAST.format(v=v, t=t)


def emit(sql, col, values, empty=False):
    if empty:
        print("-- expect-empty")
    print(sql)


print("-- Generated by postgres_literals.py; do not edit by hand.")
print("-- Each column of `e` compared with each edge value of its type in each form.")
for col, (t, values) in COLUMNS.items():
    print(f"\n-- {col} ({t})")
    for i, v in enumerate(values):
        x = lit(t, v)
        emit(f"SELECT id FROM e WHERE {col} = {x} ORDER BY id;", col, [v])
        emit(f"SELECT id FROM e WHERE {col} < {x} ORDER BY id;", col, [v], empty=i == 0)
        emit(f"SELECT id FROM e WHERE {col} >= {x} ORDER BY id;", col, [v])
        emit(f"SELECT id FROM e WHERE {col} <> {x} ORDER BY id;", col, [v])
    for a, b in zip(values, values[1:]):
        emit(f"SELECT id FROM e WHERE {col} IN ({lit(t, a)}, {lit(t, b)}) ORDER BY id;", col, [a, b])
        emit(f"SELECT id FROM e WHERE {col} BETWEEN {lit(t, a)} AND {lit(t, b)} ORDER BY id;", col, [a, b])
    emit(f"SELECT {col} = {lit(t, values[0])} AS eq, count(*) AS n FROM e GROUP BY 1 ORDER BY 1 NULLS FIRST;",
         col, [values[0]])
