    + entry(f"actions/checkout@{CHECKOUT}", "v7.0.1", CHECKOUT)
    + entry(f"actions/github-script@{GITHUB_SCRIPT}", "v9.0.0", GITHUB_SCRIPT, (f"actions/cache@{CACHE}",))
    + entry(f"github/codeql-action@{CODEQL}", "v4.39.3", CODEQL)
