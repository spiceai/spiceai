EMPTY_WORKFLOW = "name: empty\non: push\njobs:\n  noop:\n    runs-on: ubuntu-latest\n    steps:\n      - run: true\n"

ACTION_TAGS = """\
name: setup
runs:
  using: composite
  steps:
    - uses: actions/checkout@v7.0.1
"""

ACTION_PINNED = f"""\
name: setup
runs:
  using: composite
  steps:
    - uses: actions/checkout@{CHECKOUT} # v7.0.1
"""

LOCK = ".github/workflows/actions.lock"
WORKFLOW = ".github/workflows/ci.yml"
ACTION = ".github/actions/setup/action.yml"


def repo(root: Path, workflow: str, action: str, lockfile: str) -> None:
    (root / ".github/workflows").mkdir(parents=True)
    (root / ".github/actions/setup").mkdir(parents=True)
    (root / LOCK).write_text(lockfile)
    (root / WORKFLOW).write_text(workflow)
    (root / ".github/workflows/empty.yml").write_text(EMPTY_WORKFLOW)
    (root / ACTION).write_text(action)


def run(root: Path, *args: str) -> tuple[int, str, str]:
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = main([*args, str(root)])
    return code, out.getvalue(), err.getvalue()


class PinActionsToShaTest(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def read(self, path: str) -> str:
        return (self.root / path).read_text()

    def assert_tree(self, workflow: str, action: str, lockfile: str) -> None:
        self.assertEqual(self.read(WORKFLOW), workflow)
        self.assertEqual(self.read(ACTION), action)
        self.assertEqual(self.read(LOCK), lockfile)

    def test_pins_every_tag_and_keys_the_lockfile_by_commit(self) -> None:
        repo(self.root, WORKFLOW_TAGS, ACTION_TAGS, LOCK_TAGS)
        code, out, err = run(self.root)
        self.assertEqual((code, err), (0, ""))
        self.assertEqual(out, f"Pinned 6 `uses:` refs in 2 files, and keyed {LOCK} by commit.\n")
        self.assert_tree(WORKFLOW_PINNED, ACTION_PINNED, LOCK_PINNED)

    def test_keys_the_lockfile_when_the_uses_are_already_pinned(self) -> None:
        repo(self.root, WORKFLOW_PINNED, ACTION_PINNED, LOCK_TAGS)
        code, out, err = run(self.root)
        self.assertEqual((code, err), (0, ""))
        self.assertEqual(out, f"Pinned 0 `uses:` refs in 0 files, and keyed {LOCK} by commit.\n")
        self.assert_tree(WORKFLOW_PINNED, ACTION_PINNED, LOCK_PINNED)

    def test_pinning_again_changes_nothing(self) -> None:
        repo(self.root, WORKFLOW_PINNED, ACTION_PINNED, LOCK_PINNED)
        code, out, _ = run(self.root)
        self.assertEqual(code, 0)
        self.assertEqual(
            out, "Every remote `uses:` is already pinned to a full-length commit SHA, and the lockfile is keyed by it.\n"
        )
        self.assert_tree(WORKFLOW_PINNED, ACTION_PINNED, LOCK_PINNED)

    def test_missing_lockfile_entry_writes_nothing(self) -> None:
        workflow = WORKFLOW_TAGS.replace("actions/checkout@v7.0.1\n        with:", "actions/checkout@v7.0.2\n        with:")
        repo(self.root, workflow, ACTION_TAGS, LOCK_TAGS)
        code, out, err = run(self.root)
        self.assertEqual((code, out), (1, ""))
        self.assertEqual(
            err,
            f".github/workflows/ci.yml:7: {LOCK} has no entry for actions/checkout@v7.0.2\n"
            "1 `uses:` refs have no lockfile entry, so nothing was rewritten. "
            "Run `gh actions-lock` first, then run this script again.\n",
        )
        self.assert_tree(workflow, ACTION_TAGS, LOCK_TAGS)

    def test_check_fails_on_refs_the_lockfile_cannot_serve(self) -> None:
        # SHA `uses:` against a tag-keyed lockfile, which fails at workflow
        # startup, plus a short SHA.
        action = ACTION_PINNED.replace(f"actions/checkout@{CHECKOUT} # v7.0.1", "actions/checkout@3d3c42e")
        repo(self.root, WORKFLOW_PINNED, action, LOCK_TAGS)
        code, out, err = run(self.root, "--check")
        self.assertEqual(code, 1)
        self.assertEqual(
            out,
            ".github/actions/setup/action.yml:5: uses: actions/checkout@3d3c42e is not pinned to a full-length commit SHA\n"
            f".github/workflows/ci.yml:7: uses: actions/checkout@{CHECKOUT} has no {LOCK} pin "
            f"actions/checkout@{CHECKOUT} under .github/workflows/ci.yml\n"
            f".github/workflows/ci.yml:11: uses: github/codeql-action/init@{CODEQL} has no {LOCK} pin "
            f"github/codeql-action@{CODEQL} under .github/workflows/ci.yml\n"
            f".github/workflows/ci.yml:12: uses: Swatinem/rust-cache@{RUST_CACHE} has no {LOCK} pin "
            f"swatinem/rust-cache@{RUST_CACHE} under .github/workflows/ci.yml\n"
            f".github/workflows/ci.yml:13: uses: actions/github-script@{GITHUB_SCRIPT} has no {LOCK} pin "
            f"actions/github-script@{GITHUB_SCRIPT} under .github/workflows/ci.yml\n"
            f".github/workflows/ci.yml:20: uses: actions/checkout/.github/workflows/reusable.yml@{CHECKOUT} has no "
            f"{LOCK} pin actions/checkout@{CHECKOUT} under .github/workflows/ci.yml\n"
            f"{LOCK}: dependencies: actions/checkout@v7.0.1 is keyed by a tag, not the commit it locks\n"
            f"{LOCK}: dependencies: actions/github-script@v9.0.0 is keyed by a tag, not the commit it locks\n"
            f"{LOCK}: dependencies: github/codeql-action@v4.39.3 is keyed by a tag, not the commit it locks\n"
            f"{LOCK}: dependencies: swatinem/rust-cache@v2.9.3 is keyed by a tag, not the commit it locks\n",
        )
        self.assertEqual(
            err,
            "10 problems: every remote `uses:` must be pinned to a full-length commit SHA, with a lockfile entry "
            "keyed by that SHA. Fix them with `gh actions-lock` followed by `python3 scripts/pin_actions_to_sha.py`.\n",
        )
        self.assert_tree(WORKFLOW_PINNED, action, LOCK_TAGS)

    def test_check_passes_once_pinned(self) -> None:
        repo(self.root, WORKFLOW_PINNED, ACTION_PINNED, LOCK_PINNED)
        code, out, err = run(self.root, "--check")
        self.assertEqual(code, 0)
        self.assertEqual(
            (out, err), (f"Every remote `uses:` is pinned to a full-length commit SHA, and {LOCK} is keyed by it.\n", "")
        )

    def test_tag_entry_landing_on_a_commit_key_keeps_the_commit_keyed_entry(self) -> None:
        # A workflow uses actions/cache@v5.0.3 and a composite pins the same
        # commit by SHA, recorded with the tag `v5`.
        workflow = WORKFLOW_TAGS.replace("actions/checkout@v7.0.1\n        with:", "actions/cache@v5.0.3\n        with:")
        lockfile = LOCK_TAGS.replace(
            f"    '.github/workflows/ci.yml':\n        - 'actions/checkout@v7.0.1'",
            f"    '.github/workflows/ci.yml':\n        - 'actions/cache@v5.0.3'\n        - 'actions/checkout@v7.0.1'",
        ).replace(entry(f"actions/cache@{CACHE}", "v5.0.3", CACHE), entry(f"actions/cache@{CACHE}", "v5", CACHE))
        lockfile = lockfile.replace(
            entry("actions/checkout@v7.0.1", "v7.0.1", CHECKOUT),
            entry("actions/cache@v5.0.3", "v5.0.3", CACHE) + entry("actions/checkout@v7.0.1", "v7.0.1", CHECKOUT),
        )
        repo(self.root, workflow, ACTION_TAGS, lockfile)
        code, out, err = run(self.root)
        self.assertEqual((code, err), (0, ""))
        self.assertIn(f"      - uses: actions/cache@{CACHE} # v5.0.3\n", self.read(WORKFLOW))
        expected = LOCK_PINNED.replace(
            f"    '.github/workflows/ci.yml':\n",
            f"    '.github/workflows/ci.yml':\n        - 'actions/cache@{CACHE}'\n",
        ).replace(entry(f"actions/cache@{CACHE}", "v5.0.3", CACHE), entry(f"actions/cache@{CACHE}", "v5", CACHE))
        self.assertEqual(self.read(LOCK), expected)

    def test_entries_that_disagree_on_more_than_their_ref_write_nothing(self) -> None:
        lockfile = LOCK_TAGS.replace(
            entry("actions/checkout@v7.0.1", "v7.0.1", CHECKOUT),
            entry("actions/checkout@v7.0.1", "v7.0.1", CHECKOUT) + entry(f"actions/checkout@{CHECKOUT}", "v7", CHECKOUT, owner_id=1),
        )
        repo(self.root, WORKFLOW_TAGS, ACTION_TAGS, lockfile)
        code, out, err = run(self.root)
        self.assertEqual((code, out), (1, ""))
        self.assertEqual(
            err,
            f"{LOCK}: entries actions/checkout@v7.0.1 and actions/checkout@{CHECKOUT} lock one commit but record "
            "different dependencies; run `gh actions-lock --relock` to rebuild them\n",
        )
        self.assert_tree(WORKFLOW_TAGS, ACTION_TAGS, lockfile)

    def test_unknown_lockfile_layout_writes_nothing(self) -> None:
        lockfile = LOCK_TAGS.replace(
            "    '.github/workflows/empty.yml': []", "    '.github/workflows/empty.yml': ['actions/checkout@v7.0.1']"
        )
        repo(self.root, WORKFLOW_TAGS, ACTION_TAGS, lockfile)
        code, out, err = run(self.root)
        self.assertEqual((code, out), (1, ""))
        self.assertEqual(
            err,
            f"{LOCK}: unexpected line in workflows: \"'.github/workflows/empty.yml': ['actions/checkout@v7.0.1']\"; "
            "this script reads the layout `gh actions-lock` v0.4.1 writes\n",
        )
        self.assert_tree(WORKFLOW_TAGS, ACTION_TAGS, lockfile)


if __name__ == "__main__":
    unittest.main()
